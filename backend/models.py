@dataclass
class ParamDefinition:
    """Định nghĩa một tham số trong template"""
    name: str
    param_type: str = "integer"  # integer, float, choice, range, boolean
    
    # Constraints
    min_value: Optional[float] = None
    max_value: Optional[float] = None
    step: Optional[float] = None  # Bước nhảy (cho range)
    choices: Optional[List[Any]] = None  # Danh sách giá trị cho choice
    exclude: Optional[List[Any]] = None  # Giá trị loại trừ
    default_value: Optional[Any] = None
    
    # Metadata
    description: str = ""
    display_name: str = ""  # Tên hiển thị
    unit: str = ""  # Đơn vị (nếu có)
    
    # Ảnh hưởng đến độ khó
    difficulty_weight: float = 0.0  # Trọng số ảnh hưởng độ khó
    
    def validate(self, value: Any) -> tuple[bool, str]:
        """
        Kiểm tra giá trị có hợp lệ không
        Returns: (is_valid, error_message)
        """
        # Kiểm tra exclude
        if self.exclude and value in self.exclude:
            return False, f"Giá trị {value} nằm trong danh sách loại trừ"
        
        if self.param_type == "integer":
            if not isinstance(value, int):
                return False, f"Giá trị phải là số nguyên, nhận được {type(value)}"
            if self.min_value is not None and value < self.min_value:
                return False, f"Giá trị {value} nhỏ hơn min ({self.min_value})"
            if self.max_value is not None and value > self.max_value:
                return False, f"Giá trị {value} lớn hơn max ({self.max_value})"
                
        elif self.param_type == "float":
            if not isinstance(value, (int, float)):
                return False, f"Giá trị phải là số, nhận được {type(value)}"
            if self.min_value is not None and value < self.min_value:
                return False, f"Giá trị {value} nhỏ hơn min ({self.min_value})"
            if self.max_value is not None and value > self.max_value:
                return False, f"Giá trị {value} lớn hơn max ({self.max_value})"
                
        elif self.param_type == "choice":
            if self.choices and value not in self.choices:
                return False, f"Giá trị {value} không nằm trong danh sách cho phép"
                
        elif self.param_type == "boolean":
            if not isinstance(value, bool):
                return False, f"Giá trị phải là boolean"
        
        return True, ""
    
    def get_valid_values(self) -> List[Any]:
        """Lấy danh sách tất cả giá trị hợp lệ"""
        values = []
        
        if self.param_type == "choice" and self.choices:
            values = list(self.choices)
            
        elif self.param_type == "integer":
            min_v = int(self.min_value) if self.min_value is not None else -10
            max_v = int(self.max_value) if self.max_value is not None else 10
            step = int(self.step) if self.step else 1
            values = list(range(min_v, max_v + 1, step))
            
        elif self.param_type == "boolean":
            values = [True, False]
            
        elif self.param_type == "float":
            # Với float, trả về một số giá trị mẫu
            min_v = float(self.min_value) if self.min_value is not None else -10.0
            max_v = float(self.max_value) if self.max_value is not None else 10.0
            step = float(self.step) if self.step else 1.0
            v = min_v
            while v <= max_v:
                values.append(v)
                v += step
        
        # Loại bỏ các giá trị exclude
        if self.exclude:
            values = [v for v in values if v not in self.exclude]
        
        return values
    
    def to_dict(self) -> Dict:
        return {
            "name": self.name,
            "type": self.param_type,
            "min": self.min_value,
            "max": self.max_value,
            "step": self.step,
            "choices": self.choices,
            "exclude": self.exclude,
            "default": self.default_value,
            "description": self.description,
            "display_name": self.display_name,
            "difficulty_weight": self.difficulty_weight
        }
    
    @classmethod
    def from_dict(cls, name: str, data: Dict) -> 'ParamDefinition':
        return cls(
            name=name,
            param_type=data.get('type', 'integer'),
            min_value=data.get('min'),
            max_value=data.get('max'),
            step=data.get('step'),
            choices=data.get('choices'),
            exclude=data.get('exclude'),
            default_value=data.get('default'),
            description=data.get('description', ''),
            display_name=data.get('display_name', name),
            difficulty_weight=data.get('difficulty_weight', 0.0)
        )


