@dataclass
class Question(BaseModel):
    """Câu hỏi đã sinh"""
    template_id: int = 0
    solver_id: Optional[int] = None
    
    # Tham số
    param_values: Dict[str, Any] = field(default_factory=dict)
    param_hash: str = ""  # Hash của param_values để check trùng
    
    # Nội dung
    question_text: str = ""
    question_latex: str = ""
    question_html: str = ""
    
    # Đáp án
    answers: Dict[str, Answer] = field(default_factory=dict)  # A, B, C, D
    correct_answer: str = ""  # 'A', 'B', 'C', 'D'
    correct_value: Any = None
    correct_symbolic: str = ""
    
    # Lời giải
    solution: str = ""
    solution_latex: str = ""
    solution_steps: List[str] = field(default_factory=list)
    
    # NEW (V2): AI Enrichment & Explanation
    explanation: str = ""  # Lời giải chi tiết từ AI
    explanation_latex: str = ""  # LaTeX version của explanation
    ai_enriched: bool = False  # Flag: có được AI làm giàu không
    review_status: Optional[str] = None  # ReviewStatus enum value (DRAFT, AI_GENERATED, VERIFIED, REJECTED)
    
    # Metadata
    difficulty: int = 3
    quality_score: float = 0.0
    estimated_time: int = 3  # phút
    
    # Trạng thái
    status: QuestionStatus = QuestionStatus.DRAFT
    is_active: bool = True
    
    # Review
    reviewed_by: Optional[int] = None
    reviewed_at: Optional[datetime] = None
    review_notes: str = ""
    
    # Thống kê
    usage_count: int = 0
    last_used_at: Optional[datetime] = None
    correct_rate: float = 0.0  # Tỷ lệ trả lời đúng (nếu có thống kê)
    
    @staticmethod
    def compute_param_hash(param_values: Dict[str, Any]) -> str:
        """Tính hash của bộ tham số để check trùng"""
        # Sort keys để đảm bảo deterministic
        sorted_params = json.dumps(param_values, sort_keys=True)
        return hashlib.sha256(sorted_params.encode()).hexdigest()[:16]
    
    def __post_init__(self):
        if not self.param_hash and self.param_values:
            self.param_hash = self.compute_param_hash(self.param_values)
    
    def get_correct_answer_text(self) -> str:
        """Lấy text của đáp án đúng"""
        if self.correct_answer in self.answers:
            return self.answers[self.correct_answer].text
        return ""
    
    def to_dict(self) -> Dict:
        return {
            "id": self.id,
            "template_id": self.template_id,
            "param_values": self.param_values,
            "param_hash": self.param_hash,
            "question_text": self.question_text,
            "answers": {
                letter: ans.to_dict() for letter, ans in self.answers.items()
            },
            "correct_answer": self.correct_answer,
            "solution": self.solution,
            "difficulty": self.difficulty,
            "status": self.status.value if isinstance(self.status, QuestionStatus) else self.status,
            "usage_count": self.usage_count
        }
    
    def to_display_dict(self, show_answer: bool = False) -> Dict:
        """Format để hiển thị cho user"""
        result = {
            "id": self.id,
            "question": self.question_text,
            "answers": {
                letter: ans.text for letter, ans in self.answers.items()
            },
            "difficulty": self.difficulty
        }
        if show_answer:
            result["correct_answer"] = self.correct_answer
            result["solution"] = self.solution
        return result


