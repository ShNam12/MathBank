@dataclass
class Template(BaseModel):
    """Template câu hỏi - dạng bài tham số hóa"""
    subject_id: Optional[int] = None  # Liên kết với môn học
    category_id: Optional[int] = None
    code: str = ""  # Mã định danh duy nhất (vd: INT_XN_EXP)
    name: str = ""
    description: str = ""
    
    # Công thức toán học (LaTeX với placeholder)
    # Placeholder format: {{{param_name}}}
    math_formula: str = ""
    
    # Template câu hỏi (có thể chứa placeholder)
    question_template: str = ""
    
    # Định nghĩa tham số
    param_schema: Dict[str, ParamDefinition] = field(default_factory=dict)
    
    # Metadata
    difficulty_base: int = 3  # Độ khó cơ bản (1-5)
    estimated_time: int = 3  # Thời gian ước tính (phút)
    tags: List[str] = field(default_factory=list)
    hints: List[str] = field(default_factory=list)
    
    # Trạng thái
    is_active: bool = True
    is_verified: bool = False
    
    # Audit
    created_by: Optional[int] = None
    
    def validate_params(self, params: Dict[str, Any]) -> tuple[bool, str]:
        """Kiểm tra bộ tham số có hợp lệ không"""
        for name, definition in self.param_schema.items():
            if name not in params:
                if definition.default_value is None:
                    return False, f"Thiếu tham số bắt buộc: {name}"
                # Sử dụng giá trị mặc định
                params[name] = definition.default_value
            else:
                is_valid, error = definition.validate(params[name])
                if not is_valid:
                    return False, f"Tham số {name}: {error}"
        return True, ""
    
    def render_formula(self, params: Dict[str, Any]) -> str:
        """Render công thức với tham số cụ thể"""
        formula = self.math_formula
        for name, value in params.items():
            # Xử lý hiển thị số âm
            if isinstance(value, (int, float)) and value < 0:
                display_value = f"({value})"
            else:
                display_value = str(value)
            formula = formula.replace(f"{{{{{name}}}}}", display_value)
        return formula
    
    def render_question(self, params: Dict[str, Any]) -> str:
        """Render câu hỏi với tham số"""
        if self.question_template:
            question = self.question_template
            for name, value in params.items():
                question = question.replace(f"{{{{{name}}}}}", str(value))
            return question
        else:
            # Mặc định: tính giá trị của công thức
            formula = self.render_formula(params)
            return f"Tính $\\displaystyle {formula}$"
    
    def get_total_combinations(self) -> int:
        """Tính tổng số tổ hợp tham số có thể"""
        total = 1
        for definition in self.param_schema.values():
            values = definition.get_valid_values()
            if values:
                total *= len(values)
        return total
    
    def to_dict(self) -> Dict:
        return {
            "id": self.id,
            "code": self.code,
            "category_id": self.category_id,
            "name": self.name,
            "description": self.description,
            "math_formula": self.math_formula,
            "question_template": self.question_template,
            "param_schema": {
                name: p.to_dict() for name, p in self.param_schema.items()
            },
            "difficulty_base": self.difficulty_base,
            "estimated_time": self.estimated_time,
            "tags": self.tags,
            "hints": self.hints,
            "is_active": self.is_active,
            "is_verified": self.is_verified,
            "total_combinations": self.get_total_combinations()
        }


